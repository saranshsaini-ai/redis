#!/usr/bin/env runhaskell

-- Outputs the generated part of src/fmtargs.h

module Main (main) where

import Data.List (intercalate)
import System.Environment (getProgName)
import Text.Printf (printf)

maxArgs :: Int
maxArgs = 160

main :: IO ()
main = do
    progName <- getProgName
    putStrLn "/* Everything below this line is automatically generated by"
    printf " * %s. Do not manually edit. */\n\n" progName

    let argNames = intercalate ", " ["_" ++ show i | i <- [1 .. maxArgs]]
    printf "#define ARG_N(%s, N, ...) N\n\n" argNames

    let rseq = intercalate ", " [show i | i <- [maxArgs, maxArgs - 1 .. 0]]
    printf "#define RSEQ_N() %s\n\n" rseq

    putStrLn "#define COMPACT_FMT_2(fmt, value) fmt"
    mapM_
        (\i -> printf "#define COMPACT_FMT_%d(fmt, value, ...) fmt COMPACT_FMT_%d(__VA_ARGS__)\n" i (i - 2))
        [4, 6 .. maxArgs]

    putStrLn "\n#define COMPACT_VALUES_2(fmt, value) value"
    mapM_
        (\i -> printf "#define COMPACT_VALUES_%d(fmt, value, ...) value, COMPACT_VALUES_%d(__VA_ARGS__)\n" i (i - 2))
        [4, 6 .. maxArgs]

    putStrLn "\n#endif"
